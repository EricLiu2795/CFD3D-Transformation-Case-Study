bool VtkExporter::setupRecorder(const std::string &filename, const OutputGrid &grid) {
    const int imax = grid.imax, jmax = grid.jmax, kmax = grid.kmax;
    const Real dx = grid.dx, dy = grid.dy, dz = grid.dz;
    const Real xOrigin = grid.xOrigin, yOrigin = grid.yOrigin, zOrigin = grid.zOrigin;

    this->filename = filename;
    this->imax = imax;
    this->jmax = jmax;
    this->kmax = kmax;
    this->geometry.dx = dx;
    this->geometry.dy = dy;
    this->geometry.dz = dz;
    this->geometry.xOrigin = xOrigin;
    this->geometry.yOrigin = yOrigin;
    this->geometry.zOrigin = zOrigin;

    if (!mpiEnabled) {
        il = jl = kl = 1;
        iu = imax;
        ju = jmax;
        ku = kmax;
    }
    pointBuffer = new float[(iu-il+2)*(ju-jl+2)*(ku-kl+2)*3];
    cellBuffer = new float[(iu-il+2)*(ju-jl+2)*(ku-kl+2)];
    cellByteBuffer = new uint8_t[(iu-il+2)*(ju-jl+2)*(ku-kl+2)];

    return true;
}

void VtkExporter::setMpiBounds(int il, int iu, int jl, int ju, int kl, int ku) {
    this->il = il;
    this->iu = iu;
    this->jl = jl;
    this->ju = ju;
    this->kl = kl;
    this->ku = ku;
    mpiEnabled = true;
}

VtkExporter::~VtkExporter() {
    if (pointBuffer != nullptr) {
        delete[] pointBuffer;
        delete[] cellBuffer;
        delete[] cellByteBuffer;
    }
}

void VtkExporter::emitVtkHeader(FILE *file) {
    fprintf(file, "# vtk DataFile Version 2.0\n");
    fprintf(file, "Generated by fluid3d\n");
    if (useBinaryFormat) {
        fprintf(file, "BINARY\n");
    } else {
        fprintf(file, "ASCII\n");
    }
    fprintf(file, "DATASET STRUCTURED_GRID\n");
    fprintf(file, "DIMENSIONS %i %i %i\n", iu-il+2, ju-jl+2, ku-kl+2);
}

void VtkExporter::writeSnapshot(
        int stepIndex, Real time, Real *U, Real *V, Real *W, Real *P, Real *T, FlagType *Flag) {
    std::string vtkOutputPath = filename + "." + std::to_string(stepIndex) + ".vtk";
    if (partCount != 1) {
        vtkOutputPath = filename + "." + std::to_string(localRank) + "." + std::to_string(stepIndex) + ".vtk";
    }
    FILE *file = nullptr;
    if (useBinaryFormat) {
        file = fopen(vtkOutputPath.c_str(), "wb");
    } else {
        file = fopen(vtkOutputPath.c_str(), "w");
    }
    if (file == nullptr) {
        std::cerr << "Error: Couldn't open file \"" << vtkOutputPath << "\" for writing." << std::endl;
        exit(1);
    }

    emitVtkHeader(file);
    emitPointPositions(file, geometry.dx, geometry.dy, geometry.dz,
            geometry.xOrigin, geometry.yOrigin, geometry.zOrigin);
    emitPointValues(file, U, V, W, Flag);
    emitCellValues(file, P, T, Flag);

    fclose(file);
}


#define LINPT(i,j,k,l) ((((k) - (kl-1))*(ju-jl+2)*(iu-il+2) + ((j) - (jl-1))*(iu-il+2) + ((i) - (il-1)))*3 + (l))
#define LINCELL(i,j,k) (((k) - kl)*(ju-jl+1)*(iu-il+1) + ((j) - jl)*(iu-il+1) + ((i) - il))

template <typename T>
void VtkExporter::reverseByteOrder(T *values, int n) {
    auto *rawBytes = (uint8_t*)values;
    #pragma omp parallel for shared(rawBytes, values, n) default(none)
    for (int i = 0; i < n; i++) {
        uint8_t reversedBytes[sizeof(T)];
        for (size_t j = 0; j < sizeof(T); j++) {
            reversedBytes[j] = rawBytes[i * sizeof(T) + sizeof(T) - j - 1];
        }
        values[i] = *((T*)&reversedBytes);
    }
}

void VtkExporter::emitPointPositions(FILE *file,
        Real dx, Real dy, Real dz, Real xOrigin, Real yOrigin, Real zOrigin) {
    fprintf(file, "POINTS %i float\n", (iu-il+2)*(ju-jl+2)*(ku-kl+2));

    if (useBinaryFormat) {
        #pragma omp parallel for shared(dx, dy, dz, xOrigin, yOrigin, zOrigin) default(none)
        for (int k = kl-1; k <= ku; k++) {
            for (int j = jl-1; j <= ju; j++) {
                for (int i = il-1; i <= iu; i++) {
                    pointBuffer[LINPT(i,j,k,0)] = xOrigin + i * dx;
                    pointBuffer[LINPT(i,j,k,1)] = yOrigin + j * dy;
                    pointBuffer[LINPT(i,j,k,2)] = zOrigin + k * dz;
                }
            }
        }
        reverseByteOrder(pointBuffer, (iu-il+2)*(ju-jl+2)*(ku-kl+2)*3);
        fwrite(pointBuffer, sizeof(float), (iu-il+2)*(ju-jl+2)*(ku-kl+2)*3, file);
    } else {
        for (int k = kl-1; k <= ku; k++) {
            for (int j = jl-1; j <= ju; j++) {
                for (int i = il-1; i <= iu; i++) {
                    fprintf(file, "%f %f %f\n", xOrigin + i * dx, yOrigin + j * dy, zOrigin + k * dz);
                }
            }
        }
    }
}

void VtkExporter::emitPointValues(FILE *file, Real *U, Real *V, Real *W, FlagType *Flag) {
    int pointCount = (iu-il+2)*(ju-jl+2)*(ku-kl+2);
    fprintf(file, "POINT_DATA %i\n", pointCount);
    fprintf(file, "VECTORS velocity float\n");

    if (useBinaryFormat) {
        if (mpiEnabled) {
            for (int k = kl-1; k <= ku; k++) {
                for (int j = jl-1; j <= ju; j++) {
                    for (int i = il-1; i <= iu; i++) {
                        Real u = 0, v = 0, w = 0;
                        if (isWet(Flag[LINFLAG_MPI(i,j,k)])) {
                            u = (U[LINU_MPI(i,j,k)] + U[LINU_MPI(i,j+1,k)] + U[LINU_MPI(i,j,k+1)]
                                    + U[LINU_MPI(i,j+1,k+1)]) * Real(0.25);
                            v = (V[LINV_MPI(i,j,k)] + V[LINV_MPI(i+1,j,k)] + V[LINV_MPI(i,j,k+1)]
                                    + V[LINV_MPI(i+1,j,k+1)]) * Real(0.25);
                            w = (W[LINW_MPI(i,j,k)] + W[LINW_MPI(i,j+1,k)] + W[LINW_MPI(i+1,j,k)]
                                    + W[LINW_MPI(i+1,j+1,k)]) * Real(0.25);
                        }
                        pointBuffer[LINPT(i,j,k,0)] = u;
                        pointBuffer[LINPT(i,j,k,1)] = v;
                        pointBuffer[LINPT(i,j,k,2)] = w;
                    }
                }
            }
        } else {
            #pragma omp parallel for shared(U, V, W, Flag) default(none)
            for (int k = kl-1; k <= ku; k++) {
                for (int j = jl-1; j <= ju; j++) {
                    for (int i = il-1; i <= iu; i++) {
                        Real u = 0, v = 0, w = 0;
                        if (isWet(Flag[LINFLAG_NORMAL(i,j,k)])) {
                            u = (U[LINU_NORMAL(i,j,k)] + U[LINU_NORMAL(i,j+1,k)] + U[LINU_NORMAL(i,j,k+1)]
                                    + U[LINU_NORMAL(i,j+1,k+1)]) * Real(0.25);
                            v = (V[LINV_NORMAL(i,j,k)] + V[LINV_NORMAL(i+1,j,k)] + V[LINV_NORMAL(i,j,k+1)]
                                    + V[LINV_NORMAL(i+1,j,k+1)]) * Real(0.25);
                            w = (W[LINW_NORMAL(i,j,k)] + W[LINW_NORMAL(i,j+1,k)] + W[LINW_NORMAL(i+1,j,k)]
                                    + W[LINW_NORMAL(i+1,j+1,k)]) * Real(0.25);
                        }
                        pointBuffer[LINPT(i,j,k,0)] = u;
                        pointBuffer[LINPT(i,j,k,1)] = v;
                        pointBuffer[LINPT(i,j,k,2)] = w;
                    }
                }
            }
        }
        reverseByteOrder(pointBuffer, pointCount*3);
        fwrite(pointBuffer, sizeof(float), pointCount*3, file);
    } else {
        if (mpiEnabled) {
            for (int k = kl-1; k <= ku; k++) {
                for (int j = jl-1; j <= ju; j++) {
                    for (int i = il-1; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_MPI(i,j,k)])) {
                            Real u = (U[LINU_MPI(i,j,k)] + U[LINU_MPI(i,j+1,k)] + U[LINU_MPI(i,j,k+1)]
                                    + U[LINU_MPI(i,j+1,k+1)]) * Real(0.25);
                            Real v = (V[LINV_MPI(i,j,k)] + V[LINV_MPI(i+1,j,k)] + V[LINV_MPI(i,j,k+1)]
                                    + V[LINV_MPI(i+1,j,k+1)]) * Real(0.25);
                            Real w = (W[LINW_MPI(i,j,k)] + W[LINW_MPI(i,j+1,k)] + W[LINW_MPI(i+1,j,k)]
                                    + W[LINW_MPI(i+1,j+1,k)]) * Real(0.25);
                            fprintf(file, "%f %f %f\n", u, v, w);
                        } else {
                            fprintf(file, "0 0 0\n");
                        }
                    }
                }
            }
        } else {
            for (int k = kl-1; k <= ku; k++) {
                for (int j = jl-1; j <= ju; j++) {
                    for (int i = il-1; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_NORMAL(i,j,k)])) {
                            Real u = (U[LINU_NORMAL(i,j,k)] + U[LINU_NORMAL(i,j+1,k)] + U[LINU_NORMAL(i,j,k+1)]
                                    + U[LINU_NORMAL(i,j+1,k+1)]) * Real(0.25);
                            Real v = (V[LINV_NORMAL(i,j,k)] + V[LINV_NORMAL(i+1,j,k)] + V[LINV_NORMAL(i,j,k+1)]
                                    + V[LINV_NORMAL(i+1,j,k+1)]) * Real(0.25);
                            Real w = (W[LINW_NORMAL(i,j,k)] + W[LINW_NORMAL(i,j+1,k)] + W[LINW_NORMAL(i+1,j,k)]
                                    + W[LINW_NORMAL(i+1,j+1,k)]) * Real(0.25);
                            fprintf(file, "%f %f %f\n", u, v, w);
                        } else {
                            fprintf(file, "0 0 0\n");
                        }
                    }
                }
            }
        }
    }
}

void VtkExporter::emitCellValues(FILE *file, Real *P, Real *T, FlagType *Flag) {
    int cellCount = (iu-il+1)*(ju-jl+1)*(ku-kl+1);
    if (mpiEnabled) {
        fprintf(file, "CELL_DATA %i\n", cellCount);
    } else {
        fprintf(file, "CELL_DATA %i\n", cellCount);
    }
    fprintf(file, "SCALARS pressure float 1\n");
    fprintf(file, "LOOKUP_TABLE default\n");
    if (useBinaryFormat) {
        if (mpiEnabled) {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_MPI(i,j,k)])) {
                            cellBuffer[LINCELL(i,j,k)] = P[LINP_MPI(i,j,k)];
                        } else {
                            cellBuffer[LINCELL(i,j,k)] = 0;
                        }
                    }
                }
            }
        } else {
            #pragma omp parallel for shared(P, Flag) default(none)
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_NORMAL(i,j,k)])) {
                            cellBuffer[LINCELL(i,j,k)] = P[LINP_NORMAL(i,j,k)];
                        } else {
                            cellBuffer[LINCELL(i,j,k)] = 0;
                        }
                    }
                }
            }
        }
        reverseByteOrder(cellBuffer, cellCount);
        fwrite(cellBuffer, sizeof(float), cellCount, file);
    } else {
        if (mpiEnabled) {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_MPI(i,j,k)])) {
                            fprintf(file, "%f\n", P[LINP_MPI(i,j,k)]);
                        } else {
                            fprintf(file, "0\n");
                        }
                    }
                }
            }
        } else {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_NORMAL(i,j,k)])) {
                            fprintf(file, "%f\n", P[LINP_NORMAL(i,j,k)]);
                        } else {
                            fprintf(file, "0\n");
                        }
                    }
                }
            }
        }
    }

    fprintf(file, "SCALARS temperature float 1\n");
    fprintf(file, "LOOKUP_TABLE default\n");
    if (useBinaryFormat) {
        if (mpiEnabled) {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_MPI(i,j,k)])) {
                            cellBuffer[LINCELL(i,j,k)] = T[LINT_MPI(i,j,k)];
                        } else {
                            cellBuffer[LINCELL(i,j,k)] = 0;
                        }
                    }
                }
            }
        } else {
            #pragma omp parallel for shared(T, Flag) default(none)
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_NORMAL(i,j,k)])) {
                            cellBuffer[LINCELL(i,j,k)] = T[LINT_NORMAL(i,j,k)];
                        } else {
                            cellBuffer[LINCELL(i,j,k)] = 0;
                        }
                    }
                }
            }
        }
        reverseByteOrder(cellBuffer, cellCount);
        fwrite(cellBuffer, sizeof(float), cellCount, file);
    } else {
        if (mpiEnabled) {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_MPI(i,j,k)])) {
                            fprintf(file, "%f\n", T[LINT_MPI(i,j,k)]);
                        } else {
                            fprintf(file, "0\n");
                        }
                    }
                }
            }
        } else {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        if (isWet(Flag[LINFLAG_NORMAL(i,j,k)])) {
                            fprintf(file, "%f\n", T[LINT_NORMAL(i,j,k)]);
                        } else {
                            fprintf(file, "0\n");
                        }
                    }
                }
            }
        }
    }

    if (useBinaryFormat) {
        fprintf(file, "SCALARS geometry unsigned_char 1\n");
        fprintf(file, "LOOKUP_TABLE default\n");
        if (mpiEnabled) {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        cellByteBuffer[LINCELL(i,j,k)] = (Flag[LINFLAG_MPI(i,j,k)] & 0x1) == 1;
                    }
                }
            }
        } else {
            #pragma omp parallel for shared(Flag) default(none)
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        cellByteBuffer[LINCELL(i,j,k)] = (Flag[LINFLAG_NORMAL(i,j,k)] & 0x1) == 1;
                    }
                }
            }
        }
        fwrite(cellByteBuffer, sizeof(uint8_t), cellCount, file);
    } else {
        fprintf(file, "SCALARS geometry bit 1\n");
        fprintf(file, "LOOKUP_TABLE default\n");
        if (mpiEnabled) {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        fprintf(file, "%u\n", (Flag[LINFLAG_MPI(i, j, k)] & 0x1) == 1);
                    }
                }
            }
        } else {
            for (int k = kl; k <= ku; k++) {
                for (int j = jl; j <= ju; j++) {
                    for (int i = il; i <= iu; i++) {
                        fprintf(file, "%u\n", (Flag[LINFLAG_NORMAL(i, j, k)] & 0x1) == 1);
                    }
                }
            }
        }
    }
}

